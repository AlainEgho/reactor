// Builds the remake level set into play.html from levels/*.txt, and optionally writes the artifact copy.
//
// Level file format:
//   name: Long Haul
//   need: 36
//   hint: One sentence shown when the level starts.
//   gravity: on                          (optional, default off)
//   freeze-zonks: on                     (optional)
//   special: 12,5 gravity on             (optional, repeatable: a port that switches gravity;
//                                         may add "freeze-zonks" and/or "freeze-enemies")
//   ---
//   <map rows, see the key in play.html>
//
// Usage: node build.mjs [--artifact path\to\copy.html]
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const TILES = new Set(' .#RO*@XSeBoydT><^v-|+J%ZWDKliGUH' + 'I[]M/\\sgqcAVa,~F!rpPhNQtL');
const PORTS = new Set('><^v-|+');

function parseLevel(file, text) {
  const [head, body] = text.replace(/\r/g, '').split(/^---$/m);
  if (body === undefined) throw new Error(`${file}: missing the --- line between header and map`);
  const lv = { specials: [] };
  for (const line of head.split('\n').filter(l => l.trim())) {
    const m = line.match(/^([a-z-]+):\s*(.*)$/);
    if (!m) throw new Error(`${file}: cannot read header line "${line}"`);
    const [, k, v] = m;
    if (k === 'name') lv.name = v.trim();
    else if (k === 'need') lv.need = +v;
    else if (k === 'hint') lv.hint = v.trim();
    else if (k === 'gravity') lv.grav = v.trim() === 'on';
    else if (k === 'freeze-zonks') lv.freezeZ = v.trim() === 'on';
    else if (k === 'air') { lv.air = +v; if (!(lv.air > 0)) throw new Error(`${file}: air must be a number of seconds`); }
    else if (k === 'dark') lv.dark = v.trim() === 'on';
    else if (k === 'special') {
      const s = v.match(/^(\d+),(\d+)\s+gravity\s+(on|off)((?:\s+freeze-(?:zonks|enemies))*)\s*$/);
      if (!s) throw new Error(`${file}: cannot read special "${v}"`);
      lv.specials.push({ x: +s[1], y: +s[2], grav: s[3] === 'on', freezeZ: /freeze-zonks/.test(s[4]), freezeE: /freeze-enemies/.test(s[4]) });
    } else throw new Error(`${file}: unknown header "${k}"`);
  }
  lv.map = body.split('\n').filter((l, i, a) => !(l === '' && (i === 0 || i === a.length - 1)));
  while (lv.map.length && lv.map[lv.map.length - 1] === '') lv.map.pop();
  const W = lv.map[0].length, H = lv.map.length, flat = lv.map.join('');
  const bad = [];
  lv.map.forEach((r, y) => { if (r.length !== W) bad.push(`row ${y} is ${r.length} wide, expected ${W}`); });
  for (let x = 0; x < W; x++) if (lv.map[0][x] !== '#' || lv.map[H - 1][x] !== '#') { bad.push(`top or bottom border open at column ${x}`); break; }
  lv.map.forEach((r, y) => { if (r[0] !== '#' || r[r.length - 1] !== '#') bad.push(`side border open on row ${y}`); });
  for (const ch of flat) if (!TILES.has(ch)) { bad.push(`unknown tile "${ch}"`); break; }
  if ((flat.match(/@/g) || []).length !== 1) bad.push('needs exactly one @');
  if (!flat.includes('X')) bad.push('needs an Exit (X)');
  const n = re => (flat.match(re) || []).length;
  // Isotope pellets count two; every Plutonium sphere split leaves Pellets round it, six at the least.
  const supply = n(/\*/g) + 9 * n(/e/g) + 3 * n(/U/g) + 2 * n(/h/g) + 6 * n(/P/g);
  if (!lv.name) bad.push('missing name');
  if (!(lv.need >= 0)) bad.push('missing need');
  if (lv.need > supply) bad.push(`need ${lv.need} but at most ${supply} Infotrons exist`);
  if (n(/W/g) === 1) bad.push('a single teleport pad leads nowhere; use two or more');
  if (n(/[gq]/g) && !n(/s/g)) bad.push('gates without a switch never move');
  if (n(/s/g) && !n(/[gq]/g)) bad.push('a switch with no gates does nothing');
  if (n(/t/g) && !lv.air) bad.push('air tanks on a level without an air: header are pointless');
  if (n(/L/g) && !lv.dark) bad.push('lamps on a level without dark: on are pointless');
  for (const s of lv.specials) if (!PORTS.has((lv.map[s.y] || '')[s.x])) bad.push(`special at ${s.x},${s.y} is not on a port`);
  if (bad.length) throw new Error(`${file}: ${bad.join('; ')}`);
  return lv;
}

function render(levels) {
  const q = s => JSON.stringify(s);
  const out = levels.map(lv => {
    const extra = (lv.grav ? ',grav:true' : '') + (lv.freezeZ ? ',freezeZ:true' : '') +
      (lv.air ? ',air:' + lv.air : '') + (lv.dark ? ',dark:true' : '') +
      (lv.specials.length ? ',specials:' + JSON.stringify(lv.specials) : '');
    return `  {name:${q(lv.name)},need:${lv.need},hint:${q(lv.hint || '')}${extra},map:[\n` +
      lv.map.map(r => '    ' + q(r)).join(',\n') + ']}';
  });
  return '// LEVELS-START: generated by build.mjs from levels/*.txt. Edit those files, not this block.\n' +
    'const LEVELS=[\n' + out.join(',\n') + '\n];\n// LEVELS-END';
}

const files = readdirSync(join(root, 'levels')).filter(f => /^\d{3}-.*\.txt$/.test(f)).sort();
const levels = files.map(f => parseLevel(f, readFileSync(join(root, 'levels', f), 'utf8')));
const htmlPath = join(root, 'play.html');
let html = readFileSync(htmlPath, 'utf8');
const block = render(levels);
if (html.includes('// LEVELS-START')) {
  html = html.replace(/\/\/ LEVELS-START[\s\S]*?\/\/ LEVELS-END/, () => block);
} else {
  const re = /const LEVELS=\[[\s\S]*?\n\];/;
  if (!re.test(html)) throw new Error('play.html: could not find the LEVELS block');
  html = html.replace(re, () => block);
}
writeFileSync(htmlPath, html);
console.log(`Built ${levels.length} levels into play.html`);

const ai = process.argv.indexOf('--artifact');
if (ai > 0) {
  const target = process.argv[ai + 1];
  const page = html
    .replace(/<!doctype html>\s*<html[^>]*>\s*<head>\s*<meta charset="utf-8">\s*<meta name="viewport"[^>]*>\s*/i, '')
    .replace(/<\/head>\s*<body>\s*/i, '')
    .replace(/\s*<\/body>\s*<\/html>\s*$/i, '\n');
  writeFileSync(target, page);
  console.log(`Wrote the artifact copy to ${target}`);
}
